def language_codes() -> List[str]:
    return [code for code, _name in LANGUAGES]


def language_name(code: str) -> str:
    for item_code, name in LANGUAGES:
        if item_code == code:
            return name
    return "English"


def detect_language() -> str:
    """Pick the closest supported language from the OS locale."""
    try:
        tag = locale.getdefaultlocale()[0] or ""
    except (ValueError, TypeError):
        tag = ""
    tag = tag or os.environ.get("LANG", "") or os.environ.get("LANGUAGE", "")
    code = tag.replace("-", "_").split("_")[0].lower()
    return code if code in CATALOG else "en"


def resolve(code: str) -> str:
    code = (code or "").strip().lower()
    if code in ("", "auto"):
        return detect_language()
    return code if code in CATALOG else "en"


def set_language(code: str) -> str:
    global _CURRENT
    _CURRENT = resolve(code)
    return _CURRENT


def get_language() -> str:
    return _CURRENT


def t(key: str, **values: object) -> str:
    if key == "ui.choose":
        return _CHOOSE.get(_CURRENT, "choose")
    text = CATALOG.get(_CURRENT, _EN).get(key)
    if text is None:
        text = _EN.get(key, key)
    if not values:
        return text
    try:
        return text.format(**values)
    except (KeyError, IndexError, ValueError):
        return text
